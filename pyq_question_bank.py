def get_all_question_ids(bank_key):
    """Return all question IDs in a bank (flat list)."""
    bank = QUESTION_BANKS[bank_key]
    ids = []
    for section in bank["sections"]:
        for q in section["questions"]:
            ids.append(q["id"])
    return ids

def get_question_by_id(bank_key, qid):
    bank = QUESTION_BANKS[bank_key]
    for section in bank["sections"]:
        for q in section["questions"]:
            if q["id"] == qid:
                return q, section
    return None, None
