#!/usr/bin/env python3
"""
notify_telegram.py — CBSE News & Portal Updates → Telegram Channel/Group
─────────────────────────────────────────────────────────────────────────
Sends daily CBSE news digest + portal update alerts to a Telegram channel.

Setup (one-time):
  1. Create a bot: message @BotFather on Telegram → /newbot
  2. Get your BOT_TOKEN
  3. Add the bot as admin to your channel/group
  4. Get CHAT_ID:
       - For a public channel:  @YourChannelUsername
       - For a private channel: use @userinfobot or run:
           curl "https://api.telegram.org/bot<TOKEN>/getUpdates"
  5. Set GitHub Secrets:
       TELEGRAM_BOT_TOKEN = your bot token
       TELEGRAM_CHAT_ID   = your channel/group chat id

GitHub Actions env vars (add to portal-automation.yml):
  env:
    TELEGRAM_BOT_TOKEN: ${{ secrets.TELEGRAM_BOT_TOKEN }}
    TELEGRAM_CHAT_ID:   ${{ secrets.TELEGRAM_CHAT_ID }}
"""

import os
import re
import sys
import json
import urllib.request
import urllib.parse
from datetime import datetime, timezone

# ── Config ────────────────────────────────────────────────────────────────────
BOT_TOKEN = os.environ.get("TELEGRAM_BOT_TOKEN", "")
CHAT_ID   = os.environ.get("TELEGRAM_CHAT_ID", "")
PORTAL_URL = "https://cbsemock.org.in"
NEWS_URL   = f"{PORTAL_URL}/news.html"
BASE_DIR   = os.path.dirname(__file__)

# ── Telegram API ──────────────────────────────────────────────────────────────
def send_message(text: str, parse_mode: str = "HTML", disable_preview: bool = False):
    if not BOT_TOKEN or not CHAT_ID:
        print("[telegram] BOT_TOKEN or CHAT_ID not set — skipping send")
        return False
    payload = {
        "chat_id": CHAT_ID,
        "text": text,
        "parse_mode": parse_mode,
        "disable_web_page_preview": disable_preview,
    }
    url = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"
    data = json.dumps(payload).encode()
    req  = urllib.request.Request(url, data=data,
                                   headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=10) as r:
            resp = json.load(r)
            if resp.get("ok"):
                print(f"[telegram] ✓ Message sent (msg_id={resp['result']['message_id']})")
                return True
            else:
                print(f"[telegram] ✗ API error: {resp}")
                return False
    except Exception as e:
        print(f"[telegram] ✗ Request failed: {e}")
        return False

# ── Parse news.html for latest items ─────────────────────────────────────────
def get_news_items(max_items: int = 5) -> list[dict]:
    news_path = os.path.join(BASE_DIR, "news.html")
    if not os.path.exists(news_path):
        return []
    with open(news_path, encoding="utf-8") as f:
        html = f.read()
    items = []
    # Extract title + link from news.html (generated by fetch_news.py)
    for m in re.finditer(
        r'<a class="news-title" href="([^"]+)"[^>]*>([^<]+)</a>.*?<div class="news-meta">([^<]+)</div>',
        html, re.DOTALL
    ):
        link, title, meta = m.group(1), m.group(2).strip(), m.group(3).strip()
        items.append({"title": title, "link": link, "meta": meta})
        if len(items) >= max_items:
            break
    return items

# ── Message builders ──────────────────────────────────────────────────────────
def build_daily_digest() -> str:
    now   = datetime.now(timezone.utc)
    date  = now.strftime("%d %b %Y")
    items = get_news_items(5)

    lines = [
        f"📚 <b>CBSE Daily Digest — {date}</b>",
        "",
        "🔔 <b>Today's CBSE News</b>",
    ]
    if items:
        for i, it in enumerate(items, 1):
            emoji = "🔴" if i <= 2 else "📰"
            lines.append(f"{emoji} <a href=\"{it['link']}\">{it['title']}</a>")
            lines.append(f"   <i>{it['meta']}</i>")
    else:
        lines.append("No news fetched today. Check <a href=\"{NEWS_URL}\">news page</a>.")

    lines += [
        "",
        "━━━━━━━━━━━━━━━━━━━━",
        "📝 <b>Practice on CBSEMock</b>",
        f"🔗 <a href=\"{PORTAL_URL}\">cbsemock.org.in</a>",
        "",
        "📌 <b>Quick Links</b>",
        f"• <a href=\"{PORTAL_URL}/resources/maths-x.html\">Maths X</a>  "
        f"• <a href=\"{PORTAL_URL}/resources/science-x.html\">Science X</a>",
        f"• <a href=\"{PORTAL_URL}/resources/maths-xii.html\">Maths XII</a>  "
        f"• <a href=\"{PORTAL_URL}/resources/physics-xii.html\">Physics XII</a>",
        f"• <a href=\"{PORTAL_URL}/resources/chemistry-xii.html\">Chemistry XII</a>  "
        f"• <a href=\"{PORTAL_URL}/resources/biology-xii.html\">Biology XII</a>",
        "",
        "#CBSE #BoardExams #Class10 #Class12 #CBSEMock",
    ]
    return "\n".join(lines)

def build_portal_update(subject: str, url: str, details: str = "") -> str:
    return "\n".join([
        f"🆕 <b>New Portal Live: {subject}</b>",
        "",
        details or f"Full-length practice papers for {subject} are now available on CBSEMock.",
        "",
        f"📖 <b>Practice now:</b> <a href=\"{url}\">{url}</a>",
        "",
        f"🌐 All subjects: <a href=\"{PORTAL_URL}\">{PORTAL_URL}</a>",
        "",
        "#CBSE #FreeStudyMaterial #BoardExams #CBSEMock",
    ])

def build_exam_countdown() -> str:
    exam_date = datetime(2026, 2, 15, tzinfo=timezone.utc)
    now = datetime.now(timezone.utc)
    days = (exam_date - now).days
    if days <= 0:
        urgency = "🎯 Exams are here! All the best!"
    elif days <= 30:
        urgency = f"⚠️ Only <b>{days} days left!</b> Revise now."
    elif days <= 60:
        urgency = f"⏳ <b>{days} days to go.</b> Stay consistent."
    else:
        urgency = f"📅 <b>{days} days</b> to CBSE boards — build your habit now."

    return "\n".join([
        "⏰ <b>CBSE Board Exam Countdown</b>",
        "",
        urgency,
        "",
        "✅ Today's targets:",
        "  • Solve 1 practice paper",
        "  • Revise weak topics",
        "  • Check today's CBSE news",
        "",
        f"📚 <a href=\"{PORTAL_URL}\">Start practicing → cbsemock.org.in</a>",
        "",
        "#CBSECountdown #BoardExam2026",
    ])

# ── Main ──────────────────────────────────────────────────────────────────────
MODES = {
    "digest":    (build_daily_digest,    "Daily news digest"),
    "countdown": (build_exam_countdown,  "Exam countdown message"),
}

if __name__ == "__main__":
    mode = sys.argv[1] if len(sys.argv) > 1 else "digest"

    if mode == "portal_update":
        # Usage: python3 notify_telegram.py portal_update "Physics XII" "https://..." "Details..."
        subject = sys.argv[2] if len(sys.argv) > 2 else "New Subject"
        url     = sys.argv[3] if len(sys.argv) > 3 else PORTAL_URL
        details = sys.argv[4] if len(sys.argv) > 4 else ""
        msg = build_portal_update(subject, url, details)
        print(f"Sending portal update for: {subject}")
    elif mode in MODES:
        builder, label = MODES[mode]
        msg = builder()
        print(f"Sending: {label}")
    else:
        print(f"Unknown mode: {mode}")
        print(f"Usage: python3 notify_telegram.py [{'|'.join(list(MODES.keys()) + ['portal_update'])}]")
        sys.exit(1)

    print("─" * 50)
    print(msg)
    print("─" * 50)
    send_message(msg)
